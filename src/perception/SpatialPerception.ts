/**
 * 空间感知输入抽象接口（"空间感知输入" 契约）。
 * ---------------------------------------------------------------
 * 这是本仓库与"数据来源"之间的唯一边界：DroneController 只通过它获取
 * 每帧的前向障碍距离（及可选的障碍法向），**不关心**数据来自哪里。
 *
 * 设计意图（对应孵化提案的"纯算法模式 / 联合仿真模式"）：
 *   - 纯算法模式（CI / 离线仿真）：由 MockPerception 注入确定性数据，
 *     无需任何 AR 引擎或传感器即可跑通整套避障逻辑与单测；
 *   - 联合仿真模式：物理交给仿真引擎，本仓库只负责"决策 / 契约"，
 *     引擎实现本接口把感知结果喂给控制器；
 *   - 真机 / AR 模式：原 App 的 DepthSampler（深度采样）实现本接口，
 *     把 AREngine 的深度直接接入，控制器代码完全复用、零改动。
 *
 * 这样"算法"与"感知"彻底解耦：同一份 DroneController，可被 AR 引擎、
 * 仿真器、真实传感器三类数据源统一驱动。
 */
import { Vec3 } from '../core/Vec3';

export interface SpatialPerception {
  /**
   * 机头前向障碍净距（米）。
   * 口径：机体中心 → 障碍表面，沿机头前向的投影距离，已是机体到障碍的距离。
   * 返回 Infinity 表示"无障碍"或"深度不可用（这一帧防撞是盲的）"——
   * 控制器据此**不限制**速度（盲 ≠ 安全，但强行限制会让无人机僵住）。
   */
  getObstacleDistance(): number;

  /**
   * 障碍远离单位向量（可选）。由障碍表面指向无人机、远离障碍的单位向量，
   * 用于避障横移方向的参考。未实现时避障仅做"前向减速 + 保留横移"。
   */
  getObstacleNormal?(): Vec3 | null;
}
