/**
 * 空间感知输入抽象接口（"空间感知输入" 契约）。
 * ---------------------------------------------------------------
 * 这是本仓库与"数据来源"之间的唯一边界：DroneController 只通过它获取
 * 每帧的前向障碍距离（及可选的障碍法向），**不关心**数据来自哪里。
 *
 * 设计意图（对应孵化提案的"纯算法模式 / 联合仿真模式"）：
 *   - 纯算法模式（CI / 离线仿真）：由 MockPerception 注入确定性数据，
 *     无需任何 AR 引擎或传感器即可跑通整套避障逻辑与单测；
 *   - 联合仿真模式：物理交给仿真引擎，本仓库只负责"决策 / 契约"，
 *     引擎实现本接口把感知结果喂给控制器；
 *   - 真机 / AR 模式：原 App 的 DepthSampler（深度采样）实现本接口，
 *     把 AREngine 的深度直接接入，控制器代码完全复用、零改动。
 *
 * 这样"算法"与"感知"彻底解耦：同一份 DroneController，可被 AR 引擎、
 * 仿真器、真实传感器三类数据源统一驱动。
 */
import { Vec3 } from '../core/Vec3';

/**
 * 单个扇区样本（P2 多扇区扫描）。
 * ---------------------------------------------------------------
 * 与 `avoidance/VelocityObstacle.SectorInput` **结构化兼容**（字段逐一对应），
 * 因此消费方无需 import 物理层类型 —— 契约层保持"只依赖 core"的纪律。
 */
export interface SectorSample {
  /** 扇区方向单位向量 X（世界系 XZ 平面） */
  ux: number;
  /** 扇区方向单位向量 Z */
  uz: number;
  /** 沿该方向的净距（米）；Infinity = 该扇区测不到（不是"无障碍"，而是"盲"） */
  distance: number;
  /**
   * 命中点的横向偏置（米，机体右向为正）；未知时可省略（按 0 = 死区处理）。
   * 与 `VelocityObstacle.SectorInput.lateral` 同口径。
   */
  lateral?: number;
}

/**
 * 一帧多扇区扫描结果。
 * ---------------------------------------------------------------
 * 为什么需要它：单标量 `getObstacleDistance()` 只能表达"正前方多远"，
 * 无法表达"左前 1m、右前 0.4m"这类局面 —— 预测式避障（速度障碍）与
 * 绕行方向择优都必须建立在"方向 + 距离"的向量组上。
 */
export interface SectorScan {
  /** 扇区样本数组（建议等分，下标 0 = 机头前向，逆时针/左偏递增） */
  sectors: SectorSample[];
  /** 采集时刻（秒，单调时钟）；用于判定读数是否过期 */
  timestampSec: number;
  /** 本次扫描的整体置信度 0..1（0 = 完全不可信，等价于盲） */
  confidence: number;
}

export interface SpatialPerception {
  /**
   * 机头前向障碍净距（米）。
   * 口径：机体中心 → 障碍表面，沿机头前向的投影距离，已是机体到障碍的距离。
   * 返回 Infinity 表示"无障碍"或"深度不可用（这一帧防撞是盲的）"——
   * 控制器据此**不限制**速度（盲 ≠ 安全，但强行限制会让无人机僵住）。
   */
  getObstacleDistance(): number;

  /**
   * 障碍远离单位向量（可选）。由障碍表面指向无人机、远离障碍的单位向量，
   * 用于避障横移方向的参考。未实现时避障仅做"前向减速 + 保留横移"。
   */
  getObstacleNormal?(): Vec3 | null;

  /**
   * 上方净距（米，P0 垂直避障）——机体正上方最近实体沿竖直向上的净距。
   * ---------------------------------------------------------------
   * Infinity 表示"上方无实体"或"上方测不到"——与水平链路同语义：
   * 那是"这一维是盲的"，不是"可以放心爬升"（由 sensorTrust 另行分档处理）。
   * 未实现时控制器维持既有行为（垂直方向不参与避障）。
   */
  getCeilingDistance?(): number;

  /**
   * 障碍横向偏置（米，P0 绕行择优）——机体**右向为正**。
   * ---------------------------------------------------------------
   * 供 `SteeringBehavior.pickAvoidSide` 决定"往左绕还是往右绕"：
   * lateral > 0 = 障碍在机体右侧 → 必须往左绕（往右是迎面撞上去）。
   * 未实现时回退为从 `getSectorScan()` 的威胁扇区推导，再不行则取 0（死区、不挑边）。
   */
  getObstacleLateral?(): number;

  /**
   * 本机是否支持深度感知（P0 失联兜底）。
   * ---------------------------------------------------------------
   * AREngine 明确返回"不支持"时，失联永远不会自愈 —— 此时 sensorTrust 直接
   * 判 hold，不必等满 12 秒（等下去只是白飞）。未实现时按"支持"处理。
   */
  isDepthSupported?(): boolean;

  /**
   * 多扇区扫描（P2）——预测式避障与绕行择优的输入源。
   * ---------------------------------------------------------------
   * 返回 null 表示"本帧没有扇区数据"，控制器回退到单标量路径（零回归）。
   * 可选方法的意义：既有实现（AR 深度采样 / MockPerception）**一个字都不用改**，
   * 新能力按需提供，这是本仓"默认关闭、零回归"纪律在契约层的对应物。
   */
  getSectorScan?(): SectorScan | null;
}
