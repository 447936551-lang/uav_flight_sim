/**
 * 环境感知输入抽象接口（"环境感知输入" 契约）。
 * ---------------------------------------------------------------
 * 与本目录的 SpatialPerception 是**同一套设计思路的第二个实例**：
 * 算法层只声明「我需要什么环境量」，不关心这些量从哪来。
 *
 *   SpatialPerception     —— 回答「前方多远有障碍」（几何）
 *   EnvironmentPerception —— 回答「周围空气什么状态」（大气）
 *
 * 之所以必须抽象，原因与感知层完全一致：
 *   - 真实天气数据来自**网络**（HTTP 拉取气象接口），带时延、会失败、
 *     且单位随服务商变化 —— 绝不能让算法层依赖它；
 *   - CI / 离线仿真里没有网络，必须能注入确定性风场才能跑通单测；
 *   - 真机未来若接入风速传感器，同样只是"换一个实现"。
 *
 * 因此本仓库只定义接口与**纯换算**（见 src/environment/），
 * 网络取数、定时刷新、写回控制器等一切"取数"行为留在 App 侧。
 *
 * 契约约定（重要）：
 *   - 未接入 / 环境感知关闭时，实现应返回 null 或零向量 —— 算法据此
 *     退化为无风飞行，必须与原行为**逐位一致**（零回归）。
 *   - 空气密度是**相对因子**（标准海平面 = 1.0），不是绝对密度值，
 *     这样不同数据源无需关心单位与海拔基准。
 */
import { Vec3 } from '../core/Vec3';

export interface EnvironmentPerception {
  /**
   * 风速矢量（m/s，AR 世界系：X 右 / Y 上 / Z 朝用户）。
   * 语义：空气相对地面的**运动速度**，即"空气往哪吹"。
   * 动力学层据此计算**相对气流**阻力（v_drone − v_wind），
   * 因此风不再是一个"硬加在机身上的加速度"，而是空气本身在动。
   * 返回 null 表示无风 / 未接入。
   */
  getWindVelocity(): Vec3 | null;

  /**
   * 空气密度相对因子（标准海平面 = 1.0）。可选。
   * 高温 / 低压 → < 1（空气稀薄，同转速升力更小）；
   * 低温 / 高压 → > 1。未实现时视为 1.0。
   */
  getAirDensity?(): number;
}
